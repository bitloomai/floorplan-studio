/* `mcp.js` writes real project files through `store.js`, whose data directory
 * is fixed at require() time from `FPS_DATA_DIR` — already resolved for every
 * other test in this process, to this app's own `app/data`. Exercising it
 * here in-process would mean every assertion below either corrupts that real
 * data or has to fake out `store` some other way. Instead each scenario runs
 * in its own throwaway Node process with its own temp data directory, and
 * reports back one line of JSON per assertion — the one place in this file
 * that shells out, and only to `process.execPath` (this same Node), never a
 * shell, so there is nothing to quote or escape. */
function runInIsolatedDataDir(scriptLines, envExtra) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'fps-mcp-'));
  const scriptFile = path.join(dir, 'scenario.js');
  fs.writeFileSync(scriptFile, scriptLines.join('\n'), 'utf8');
  try {
    const out = execFileSync(process.execPath, [scriptFile], {
      env: Object.assign({}, process.env, { FPS_DATA_DIR: path.join(dir, 'data') }, envExtra || {}),
      encoding: 'utf8',
      timeout: 20000,
    });
    const lastLine = out.trim().split('\n').filter(Boolean).pop() || '[]';
    return JSON.parse(lastLine);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

