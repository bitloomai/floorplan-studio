/* A fake Home Assistant, speaking the real protocol, so connect/auth/send and
 * every dashboard command below are exercised rather than pattern-matched. */
function FakeHA(opts) {
  const o = opts || {};
  const store = o.store || { dashboards: [], resources: [], configs: {} };
  return function FakeSocket(url) {
    const self = this;
    this.url = url;
    const ls = { message: [], error: [], close: [] };
    this.addEventListener = (k, fn) => { (ls[k] = ls[k] || []).push(fn); };
    this.close = () => { for (const fn of ls.close) fn(); };
    const emit = (obj) => setTimeout(() => { for (const fn of ls.message) fn({ data: JSON.stringify(obj) }); }, 0);
    setTimeout(() => emit({ type: 'auth_required', ha_version: '2026.8.0' }), 0);
    this.send = (raw) => {
      const m = JSON.parse(raw);
      if (m.type === 'auth') {
        return emit(m.access_token === (o.token || 'good')
          ? { type: 'auth_ok', ha_version: '2026.8.0' } : { type: 'auth_invalid' });
      }
      const ok = (result) => emit({ id: m.id, type: 'result', success: true, result });
      const err = (message) => emit({ id: m.id, type: 'result', success: false, error: { message } });
      switch (m.type) {
        case 'get_states': return ok(o.states || []);
        case 'lovelace/dashboards/list': return ok(store.dashboards);
        case 'lovelace/dashboards/create': {
          const d = { id: 'd' + (store.dashboards.length + 1), url_path: m.url_path, title: m.title, icon: m.icon };
          store.dashboards.push(d); return ok(d);
        }
        case 'lovelace/resources': return ok(store.resources);
        case 'lovelace/resources/create': {
          const r = { id: 'r' + (store.resources.length + 1), url: m.url, type: m.res_type };
          store.resources.push(r); return ok(r);
        }
        case 'lovelace/resources/update': {
          const r = store.resources.find((x) => x.id === m.resource_id);
          if (r) r.url = m.url; return ok(r);
        }
        case 'lovelace/resources/delete': {
          store.resources = store.resources.filter((x) => x.id !== m.resource_id);
          return ok(null);
        }
        case 'lovelace/config':
          return store.configs[m.url_path] ? ok(store.configs[m.url_path]) : err('config_not_found');
        case 'lovelace/config/save':
          store.configs[m.url_path] = m.config; return ok(null);
        default: return err('unknown command ' + m.type);
      }
    };
    this._store = store;
    FakeSocket.last = self;
  };
}

