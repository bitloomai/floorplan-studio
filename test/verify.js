/* `mcp_enabled` is checked in server.js, above mcp.js entirely — server.js is
 * a run-to-listen entrypoint (store.init().then(() => server.listen(...))),
 * not a library other files require, so exercising this one option means
 * actually booting it as a child process, the only place this particular
 * wiring lives. */
/* Windows sometimes has a high port in its own reserved/excluded range, which
 * fails as `EACCES` — nothing to do with this app — rather than the
 * `EADDRINUSE` a real collision would give. Retried on a fresh random port a
 * few times before giving up, same as a collision would be. */
async function withServer(options, run, readyPattern) {
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      return await withServerOnce(options, run, readyPattern);
    } catch (e) {
      /* `server exited early` too: a bind failure is an uncaught exception in
       * the child, and the stderr carrying the actual EADDRINUSE has often not
       * arrived by the time `close` fires — so the retry this loop exists for
       * was being skipped on the exact failure it was written for. The TLS case
       * picks a SECOND random port, which is the one that collides. A genuine
       * startup fault still fails, three attempts later. */
      if (attempt === 3 || !/EACCES|EADDRINUSE|server exited early/.test(e.message)) throw e;
    }
  }
}

function withServerOnce(options, run, readyPattern) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'fps-server-'));
  const optionsFile = path.join(dir, 'options.json');
  fs.writeFileSync(optionsFile, JSON.stringify(options || {}), 'utf8');
  /* server.js logs the PORT it was TOLD to listen on, not what the OS handed
   * back, so `0` (ephemeral) is unusable here — the log line would always
   * read ":0" no matter what port was actually bound. A random high port is
   * a small, accepted collision risk instead. */
  const port = 40000 + Math.floor(Math.random() * 10000);
  const ready = readyPattern || /listening on/;
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, [path.join(APP, 'server.js')], {
      env: Object.assign({}, process.env, {
        FPS_DATA_DIR: path.join(dir, 'data'),
        FPS_OPTIONS_FILE: optionsFile,
        FPS_PORT: String(port),
        PORT: '',
      }),
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    let out = '';
    let settled = false;
    /* `kill()` only ASKS the process to stop — on Windows in particular, node
     * has crashed here before (a libuv `UV_HANDLE_CLOSING` assertion) when
     * this whole script's own `process.exit()` ran while a killed child's
     * pipe handles were still mid-teardown. Waiting for the child's own
     * "exit" before resolving is what actually avoids that, not the kill()
     * call itself. */
    function finish(settle, value) {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      const done = () => { fs.rmSync(dir, { recursive: true, force: true }); settle(value); };
      if (child.exitCode !== null || child.signalCode !== null) { done(); return; }
      child.once('exit', done);
      child.kill();
    }
    const timer = setTimeout(() => finish(reject, new Error('server did not start in time: ' + out)), 10000);
    child.on('error', (e) => finish(reject, e));
    /* A bind failure is an uncaught exception in the child (server.js never
     * attaches a `server.on('error', ...)`), which exits the process almost
     * immediately — worth noticing here rather than waiting out the full 10s
     * timeout above for something that already happened. `'close'`, not
     * `'exit'`, because `'exit'` can fire before the stderr data carrying the
     * actual error text has finished arriving. */
    child.on('close', (code) => { if (code) finish(reject, new Error('server exited early (' + code + '): ' + out)); });
    child.stderr.on('data', (d) => { out += d.toString(); });
    child.stdout.on('data', (d) => {
      out += d.toString();
      if (settled || !ready.test(out)) return;
      Promise.resolve(run(port)).then((result) => finish(resolve, result), (e) => finish(reject, e));
    });
  });
}

