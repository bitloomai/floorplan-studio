/* Node's global `fetch` is undici-based and does not honour a plain
 * `https.Agent` passed as `agent` — it still validates against the real
 * trust store and rejects a self-signed cert regardless. A raw `https.request`
 * is the one API that actually respects `rejectUnauthorized: false`, which is
 * all this needs: a throwaway local fixture cert, not a claim about how a
 * real MCP client should ever be configured. */
function httpsPostJson(port, body) {
  return new Promise((resolve, reject) => {
    const payload = JSON.stringify(body);
    const req = https.request({
      hostname: '127.0.0.1', port, path: '/mcp', method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': Buffer.byteLength(payload) },
      rejectUnauthorized: false,
    }, (res) => {
      let data = '';
      res.on('data', (c) => { data += c; });
      res.on('end', () => resolve({ status: res.statusCode, body: JSON.parse(data) }));
    });
    req.on('error', reject);
    req.end(payload);
  });
}

