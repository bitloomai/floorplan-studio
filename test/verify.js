/* An XML comment may not contain a double hyphen. It is legal in every other
 * kind of comment a person writes all day, and the failure is silent: the file
 * simply stops rendering, everywhere, with no error unless you happen to open
 * it in a browser tab. It bit this repository twice while the art was being
 * drawn, which is exactly what a test is for. */
function badXmlComments(src) {
  const bad = [];
  let i = 0;
  while ((i = src.indexOf('<!--', i)) !== -1) {
    const end = src.indexOf('-->', i + 4);
    if (end === -1) { bad.push('unterminated'); break; }
    if (src.slice(i + 4, end).includes('--')) bad.push('line ' + (src.slice(0, i).split('\n').length));
    i = end + 3;
  }
  return bad;
}
